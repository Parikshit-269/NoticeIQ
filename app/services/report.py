"""Standalone, printable HTML report for one analysed document."""
from html import escape

from app.services.analyzer import missing_categories

LABELS = {"deadline": "Deadlines", "eligibility": "Eligibility conditions", "fee": "Fees & amounts",
          "document": "Required documents", "date": "Other dates mentioned"}


def render_report(doc: dict) -> str:
    e = lambda v: escape(str(v)) if v is not None else ""  # noqa: E731
    parts = [f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>NoticeIQ report – {e(doc['title'])}</title>
<style>body{{font-family:system-ui,sans-serif;max-width:900px;margin:24px auto;padding:0 16px;color:#16261d}}
h1{{color:#166534}}h2{{border-bottom:2px solid #bbf7d0;padding-bottom:4px;margin-top:28px}}
table{{border-collapse:collapse;width:100%;font-size:14px}}td,th{{border:1px solid #d1e7d9;padding:6px 8px;text-align:left;vertical-align:top}}
th{{background:#f0fdf4}}.warn{{background:#fef9c3;padding:8px 12px;border-radius:6px}}.muted{{color:#5b6b61}}</style></head><body>
<h1>{e(doc['title'])}</h1>
<p class="muted">File: {e(doc['filename'])} · {doc['page_count']} page(s) · uploaded {e(doc['uploaded_at'])} UTC</p>"""]
    if doc["ocr_pages"]:
        parts.append(f'<p class="warn">Pages {", ".join(map(str, doc["ocr_pages"]))} appear to be scanned images. '
                     "Their text was not read; facts on those pages are missing from this report.</p>")
    missing = missing_categories(doc["facts"])
    if missing:
        parts.append('<p class="warn">Not found in the document: ' + ", ".join(LABELS[m] for m in missing) + ".</p>")
    for cat in ("deadline", "eligibility", "fee", "document", "date"):
        facts = [f for f in doc["facts"] if f["category"] == cat]
        if not facts:
            continue
        parts.append(f"<h2>{LABELS[cat]}</h2><table><tr><th>Value</th><th>Context</th><th>Page</th>"
                     "<th>Confidence</th><th>Evidence</th></tr>")
        for f in facts:
            note = f"<br><em>{e(f['note'])}</em>" if f.get("note") else ""
            parts.append(f"<tr><td>{e(f['value'])}{' → ' + e(f['normalized']) if cat in ('deadline', 'date') else ''}</td>"
                         f"<td>{e(f['label'])}</td><td>{f['page']}</td><td>{e(f['confidence'])}{note}</td>"
                         f"<td>{e(f['evidence'])}</td></tr>")
        parts.append("</table>")
    parts.append("<h2>Action checklist</h2><table><tr><th>Done</th><th>Task</th><th>Due</th><th>Page</th></tr>")
    for t in doc["tasks"]:
        parts.append(f"<tr><td>{'✔' if t['done'] else '☐'}</td><td>{e(t['title'])}</td>"
                     f"<td>{e(t['due_date'] or '—')}</td><td>{e(t['source_page'] or '')}</td></tr>")
    parts.append("</table><p class='muted'>Generated by NoticeIQ using rule-based extraction. "
                 "Always verify against the original notice.</p></body></html>")
    return "".join(parts)
